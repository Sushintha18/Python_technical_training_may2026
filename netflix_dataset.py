import pandas as pd

# Drop irrelevant original columns and the target variable 'type'
# Dropping 'country' as 'target_country' is derived from it and being used.
# Dropping 'platform' as it seems to be a constant value 'Netflix'.
cols_to_drop = ['show_id', 'title', 'description', 'type', 'country', 'platform']
x = df.drop(cols_to_drop, axis=1)
y = df['type'] # Target variable

# Feature Engineering for 'date_added'
# Convert 'date_added' to datetime objects, handling potential parsing errors
x['date_added'] = pd.to_datetime(x['date_added'], errors='coerce')
x['year_added'] = x['date_added'].dt.year.fillna(0).astype(int) # Fill NaN years with 0
x['month_added'] = x['date_added'].dt.month.fillna(0).astype(int) # Fill NaN months with 0
x = x.drop('date_added', axis=1) # Drop the original date_added column

# Feature Engineering for 'duration'
def extract_duration_value(duration_str):
    if pd.isna(duration_str):
        return 0, 0 # Return 0 for both minutes and seasons if NaN
    parts = duration_str.split(' ')
    if len(parts) == 2:
        try:
            value = int(parts[0])
            unit = parts[1]
            if 'min' in unit:
                return value, 0 # Return minutes, 0 seasons
            elif 'Season' in unit:
                return 0, value # Return 0 minutes, seasons
        except ValueError:
            return 0, 0 # Handle cases where conversion to int fails
    return 0, 0 # Default for unexpected formats

x['duration_minutes'], x['duration_seasons'] = zip(*x['duration'].apply(extract_duration_value))
x = x.drop('duration', axis=1) # Drop the original duration column

# One-hot encode categorical features
# 'release_year' is already numerical (int64)
categorical_cols = ['rating', 'listed_in', 'language', 'target_country']
x = pd.get_dummies(x, columns=categorical_cols, drop_first=True) # drop_first to avoid multicollinearity

X_train,X_test,y_train,y_test=train_test_split(x,y,test_size=0.3,random_state=42)

model = LogisticRegression(max_iter=1000)
model.fit(X_train, y_train)
print("Model Trained")
y_pred = model.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)
cm = confusion_matrix(y_test, y_pred)
report = classification_report(y_test, y_pred)

print(f"Accuracy: {accuracy:.4f}")
